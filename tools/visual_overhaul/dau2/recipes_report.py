"""Markdown renderers for the P1/P2 recipes: the 33-move design shortlist and the full per-move recipe sheets."""
from __future__ import annotations


def _fmt_part(r: dict) -> str:
    k = r["kind"]
    if k == "design_note":
        return f"DESIGN NOTE - {r['title']}: {r['note']}"
    if k == "native_keep":
        return f"keep native emitters {r['emitters']}" + (f" ({r['note']})" if r["note"] else "")
    t = f"{r['at']['anchor']}{r['at']['offset']:+d} (+{r['len_frames']}f)"
    if k == "native_borrow":
        c = r["cost"]
        return f"{r['role']} @ {t}: borrow Platinum `{r['spa']}.spa` emitters {c['emitters']} - {r['note']} (peak {c['peak_live_particles']} quads, {c['texture_vram_bytes']} B tex)"
    if k == "sheet":
        v = f" [{r['palette_variant']}]" if r["palette_variant"] else ""
        return f"{r['role']} @ {t}: installed `{r['sheet']}`{v} / `{r['seq']}` x{r['copies']} - {r['macro']}" + (f" - {r['note']}" if r["note"] else "")
    if k == "donor":
        src = "; ".join(f"{c['source_game'].split(' (')[0]} `{c['archive_path'].rsplit('/', 1)[-1]}{('#' + c['archive_member']) if c['archive_member'] else ''}` ({c['tile_count']}t)" for c in r["cells"])
        return f"{r['role']} @ {t}: NEW donor cell(s) {src} x{r['copies']} - {r['macro']}" + (f" - {r['note']}" if r["note"] else "")
    return f"{r['role']} @ {r['at']['anchor']}{r['at']['offset']:+d}: {r['macro']}" + (f" - {r['note']}" if r["note"] else "")


def _line_cost(r: dict) -> str:
    c = r["cost"]
    return (f"+{c['new_obj_tiles']} new OBJ tiles; peak {c['concurrent_obj_tiles_peak']}t / {c['concurrent_sprite_managers_peak']} mgr / {c['concurrent_oam_peak']} OAM; "
            f"~{c['gx_particle_quads_peak_est']} GX quads, {c['particle_texture_vram_bytes_est']} B tex; ~{r['timing']['estimated_total_frames']}f ({r['timing']['delta_vs_native_frames']:+d} vs native lb)")


def shortlist_markdown(d: dict) -> str:
    L = ["# DAU2 - P1/P2 design shortlist (33 moves, PROVISIONAL)", "",
         "Generated by `dau2_curate.py recipes`. **Every selection is provisional until it is built, run in an emulator and accepted by the owner; nothing is implemented.** "
         "One primary recommendation per move plus up to two alternatives. Native Platinum emitters and new Opal sprite sequences are combined wherever that is strongest; "
         "no donor game's style is privileged (assets are combined across all libraries by quality and cohesion). Costs are static estimates, not measurements. "
         "Full recipes (launch / travel / impact / timing / provenance / compatibility / cost): `RECIPES_P1_P2.md`, `RECIPES_P1_P2.json`.", "",
         "| Move | Primary | Strategy | Donor / source mix | New tiles | Peak mgr/OAM | Alternatives | Flags |", "|---|---|---|---|---:|---|---|---|"]
    for m in d["moves"]:
        p = m["primary"]
        libs = sorted({c["source_game"].split(" (")[0].replace("Pokemon ", "") for r in p["parts"] if r["kind"] == "donor" for c in r["cells"]})
        mix = ["native " + (m["native"]["spa"] or "script")] + (["borrow " + ", ".join(p["compatibility"]["native_borrow"])] if p["compatibility"]["native_borrow"] else []) \
            + (["sheets " + ", ".join(s.replace("opal_", "") for s in p["compatibility"]["installed_sheets_reused"])] if p["compatibility"]["installed_sheets_reused"] else []) + (["donor " + ", ".join(libs)] if libs else [])
        flags = []
        if p["strategy"] == "custom_composite":
            flags.append("custom composite")
        if p["compatibility"]["needs_new_palette_variant"]:
            flags.append("new palette variant")
        if p["compatibility"]["runtime_palette_dependency"] != ["none"]:
            flags.append("palette dependency")
        flags += [n.split(":")[0] for n in p["notes"]]
        c = p["cost"]
        L.append(f"| {m['move']} ({m['tier'][:2]}) | **{p['name']}** | {p['strategy']} | {'; '.join(mix)} | {c['new_obj_tiles']} | {c['concurrent_sprite_managers_peak']}/{c['concurrent_oam_peak']} | "
                 + " / ".join(f"{a['name']} ({a['strategy']}, +{a['cost']['new_obj_tiles']}t)" for a in m["alternatives"]) + f" | {', '.join(flags) or '-'} |")
    from collections import Counter
    games, kinds = Counter(), Counter()
    for m in d["moves"]:
        for r in m["primary"]["parts"]:
            kinds[r["kind"]] += 1
            if r["kind"] == "donor":
                for c in r["cells"]:
                    games[c["source_game"].split(" (")[0].replace("Pokemon ", "")] += 1
    L += ["", "## Source mix of the 33 primaries", "",
          "Parts by kind: " + ", ".join(f"{k} {v}" for k, v in sorted(kinds.items())) + ". New donor cells by game: " + ", ".join(f"{k} {v}" for k, v in games.most_common()) + ". "
          "No donor style was preferred: each part was taken from whichever pool showed the most legible, role-correct art in the rendered boards. Emerald supplies most *small named sprites* "
          "(its sprites are named and were the most legible stills), while Ranger 2 / PMD Sky / Diamond supply the larger shaded or spiral art where nothing else fit. "
          "If you want a different balance, the alternatives swap sources without changing the choreography.", ""]
    tot = sum(m["primary"]["cost"]["new_obj_tiles"] for m in d["moves"])
    L += ["", f"Primaries add **{tot}** new OBJ tiles in total across 33 moves ({sum(1 for m in d['moves'] if m['primary']['cost']['new_obj_tiles'] == 0)} add none); "
          f"{sum(1 for m in d['moves'] if m['primary']['strategy'] == 'custom_composite')} are custom composites (Double Team, Hypnosis, Swords Dance).", ""]
    return "\n".join(L) + "\n"


def recipes_markdown(d: dict) -> str:
    L = ["# DAU2 - P1/P2 animation recipes (PROVISIONAL until runtime verified)", "",
         "Per move: native baseline, one primary and up to two alternatives. Parts show role, timing (anchor `L` = script start, `H` = native hit beat; frames at 60 fps), "
         "source and the Opal macro. See `DESIGN_SHORTLIST.md` for the one-page view. Provisional: not built, not run, not approved.", ""]
    for m in d["moves"]:
        n = m["native"]
        L += [f"## {m['move']} ({m['tier'][:2]}, `{m['template']}`) - {m['visual_intent']}", "",
              f"Native: `{n['spa'] or 'no particle archive'}` emitters {sorted({e['index'] for e in (n['emitters'] or [])})}, lower-bound duration {n['duration_lower_bound_frames']}f, "
              f"hit beat H = {m['anchors']['H_lb']} (budget {m['anchors']['H']}); existing sprite resources: {sorted(set(n['sprite_resources'] or [])) or 'none'}. Script: `{m['anim_script']}`.", ""]
        for r in [m["primary"], *m["alternatives"]]:
            tag = "PRIMARY" if r["key"] == "primary" else f"ALTERNATIVE {r['key'][-1]}"
            L += [f"### {tag}: {r['name']} ({r['strategy']}) - PROVISIONAL", "", r["summary"], "", f"*Why:* {r['why']}", ""]
            L += [f"* {_fmt_part(p)}" for p in r["parts"]]
            comp = r["compatibility"]
            nd = comp["new_donor_sheet"]
            L += ["", f"*Compatibility:* macros {', '.join(comp['macros']) or '-'}; installed sheets {', '.join(comp['installed_sheets_reused']) or 'none'}; "
                  + (f"new sheet `{nd['name']}` ({nd['tiles']} tiles, <= {nd['colours_upper_bound']} colours{', palette fold needed' if nd['palette_fold_required'] else ''}); " if nd else "no new sheet; ")
                  + f"runtime palette dependency: {', '.join(comp['runtime_palette_dependency'])}; decode: {', '.join(comp['decode_confidence'])}."
                  + (f" Needs: {'; '.join(comp['needs_new_palette_variant'])}." if comp["needs_new_palette_variant"] else ""),
                  f"*Cost (static estimate):* {_line_cost(r)}." + (f" Notes: {' | '.join(r['notes'])}" if r["notes"] else ""), ""]
    return "\n".join(L) + "\n"
