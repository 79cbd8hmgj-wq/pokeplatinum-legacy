def write_palette(relative_path: str, colors: list[tuple[int, int, int]]) -> None:
    if len(colors) != 16:
        raise ValueError(f"{relative_path}: expected 16 colors, got {len(colors)}")

    path = TERRAIN_DIR / relative_path
    lines = ["JASC-PAL", "0100", "16"]
    lines.extend(f"{r} {g} {b}" for r, g, b in colors)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    for relative_path, colors in PALETTES.items():
        write_palette(relative_path, colors)


if __name__ == "__main__":
    main()
