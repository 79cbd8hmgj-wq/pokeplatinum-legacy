#!/usr/bin/env python3
"""B8-02 measured-budget report: static per-script resource peaks (from the cue-trace baseline), per-sheet OBJ cost, and optional
ROM/NARC size deltas between two meson build directories.

  opal_budget_report.py [--build DIR] [--base-build DIR] > docs/visual_overhaul/opal_b2_b8/BUDGET_TABLES.md

Peaks are *static upper bounds* from symbolic execution (they assume every spawned FX instance is live for its full lifetime);
nothing here is an emulator or hardware measurement.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs/visual_overhaul/opal_b2_b8"
NARCS = ["res/graphics/battle/moves/anim_ncgr.narc", "res/graphics/battle/moves/anim_nclr.narc", "res/graphics/battle/moves/anim_ncer.narc",
         "res/graphics/battle/moves/anim_nanr.narc", "res/moves/anim_scripts.narc", "res/battle/scripts/common_anims/anim_subscripts.narc",
         "res/battle/scripts/subscripts/sub_seq.narc"]


def size(d, rel):
    p = Path(d) / rel
    return p.stat().st_size if p.exists() else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--build", type=Path)
    ap.add_argument("--base-build", type=Path)
    a = ap.parse_args()
    trace = json.loads((OUT / "cue_trace_baseline.json").read_text())
    print("# Opal B2-B8 budget tables (generated by tools/visual_overhaul/opal_budget_report.py)\n")
    print("## Installed FX sheets\n")
    print("| Sheet | OBJ tiles | char bytes | opaque colours | palette variants | sequences |\n|---|---:|---:|---:|---:|---:|")
    total = 0
    for p in sorted((ROOT / "docs/visual_overhaul/opal_installed_fx").glob("opal_*.provenance.json")):
        d = json.loads(p.read_text())
        total += d["obj_tiles"]
        print(f"| {d['name']} | {d['obj_tiles']} | {d['obj_tiles'] * 32} | {len(d['palette_colours_rgb555'])} | {len(d['palette_variants_rgb555'])} | {len(d['sequences'])} |")
    print(f"\nInstalled total: {total} tiles ({total * 32} bytes) of OBJ character data across all sheets; per-script *concurrent* peaks below.\n")
    print("## Static per-script peaks (upper bounds, all control-flow paths)\n")
    print("| Script | paths | frames (lower bound) | sprite managers | live Opal FX sprites | OAM entries (bound) | OBJ char tiles |\n|---|---:|---:|---:|---:|---:|---:|")
    for k, v in trace.items():
        print(f"| {k} | {len(v)} | {max(r['frames_lower_bound'] for r in v)} | {max(r['peak_sprite_managers'] for r in v)} | {max(r['peak_live_fx_sprites'] for r in v)} | {max(r['peak_oam_entries_upper_bound'] for r in v)} | {max(r['peak_obj_char_tiles'] for r in v)} |")
    print("\nPolicy caps enforced by opal_cue_trace.py: <= 2 concurrent sprite managers (one OBJ palette each), <= 400 concurrent OBJ char tiles (12.5 KiB of the 64 KiB main-OBJ bank), <= 40 concurrent Opal OAM entries (of 128), FX lifetime <= 180 frames, camera cue <= 90 frames.\n")
    if a.build and a.base_build:
        print("## Archive sizes: B1 head (b85106dc) vs this PR\n")
        print("| Archive | before (bytes) | after (bytes) | delta |\n|---|---:|---:|---:|")
        for rel in NARCS:
            b, n = size(a.base_build, rel), size(a.build, rel)
            if b is None or n is None:
                continue
            print(f"| {rel} | {b} | {n} | {n - b:+d} |")
        print("\n`main.nef` is deliberately not compared: its size is dominated by DWARF line tables that depend on the checkout path.")
        print()


if __name__ == "__main__":
    main()
